import hre from "hardhat";
import fs from "fs";
import path from "path";

/*
 * Audit M-7 (prep) and H-3 / M-5 roll-out for the live ESADepositVault on Base.
 *
 * THIS SCRIPT SENDS NOTHING. It never asks for a signer. It reads chain state (read-only), checks
 * the new implementation's storage layout against the network manifest, and writes Safe
 * Transaction Builder batches for the Ops Safe to review and execute. The owner runs it; the
 * audit fix pass did not.
 *
 *   VAULT_IMPL=0x... RELAYER=0x... USDC=0x... [NEW_CLRUSD=0x...] \
 *     npx hardhat run scripts/migrate_vault_clrusd.ts --network base
 *
 * Phases (each a separate Safe batch, in this order):
 *
 *   1. upgrade   -- upgradeToAndCall(VAULT_IMPL, setAcceptedToken(USDC, true)); grant RELAYER_ROLE
 *                   to the relayer; revoke OPERATOR_ROLE from it (and from anyone else the survey
 *                   lists). The upgrade and the accepted-token call MUST travel together: the new
 *                   single-token rule (M-5) reads a fresh storage slot that starts at zero, so an
 *                   upgrade on its own stops all deposits and redemptions until it is set.
 *                   Deploy VAULT_IMPL beforehand with `upgrades.prepareUpgrade` (it validates the
 *                   layout against .openzeppelin/base.json); this script re-runs that validation.
 *
 *   2. drain     -- not a transaction. The old CLRUSD (0xa7a2...6583) cannot be upgraded, and
 *                   `setClrusd` only accepts a new token once the old supply is zero, so every
 *                   holder must redeem the old token first (members redeem; the co-op redeems
 *                   anything it holds). The script prints the outstanding supply.
 *
 *   3. repoint   -- once supply is zero: grant the vault mint/burn on NEW_CLRUSD (deployed by
 *                   deploy/21_deploy_ClearUSDUpgradeable.ts), then setClrusd(NEW_CLRUSD). Members
 *                   then deposit again and receive the lockable, seizable token.
 */

const { ethers, upgrades, network } = hre as typeof hre & {
  upgrades: typeof import("@openzeppelin/hardhat-upgrades").upgrades;
};

const VAULT_PROXY: Record<string, string> = {
  "base-sepolia": "0x7bA87Eb0DC8ADF4a6CbE9f90d05A782De0F740cD",
  base: "0x0CfE6aFB053474cE4Ff744a1fe864C82c173a1C1",
};

type SafeTx = { to: string; value: string; data: string; contractMethod?: unknown; contractInputsValues?: unknown };

function batch(chainId: bigint, name: string, transactions: SafeTx[]) {
  return {
    version: "1.0",
    chainId: chainId.toString(),
    createdAt: Date.now(),
    meta: { name, description: "Generated by scripts/migrate_vault_clrusd.ts (audit M-7 / H-3 / M-5)" },
    transactions,
  };
}

function need(name: string): string {
  const value = process.env[name]?.trim();
  if (!value || !ethers.isAddress(value)) throw new Error(`Set ${name} to an address.`);
  return ethers.getAddress(value);
}

async function main() {
  const proxy = VAULT_PROXY[network.name];
  if (!proxy) throw new Error(`No vault proxy configured for network ${network.name}`);
  const impl = need("VAULT_IMPL");
  const relayer = need("RELAYER");
  const usdc = need("USDC");
  const newClrusd = process.env.NEW_CLRUSD?.trim() ? need("NEW_CLRUSD") : undefined;
  const { chainId } = await ethers.provider.getNetwork();

  // Layout check against the manifest (no transaction; throws on an unsafe layout).
  const Vault = await ethers.getContractFactory("ESADepositVault");
  await upgrades.validateUpgrade(proxy, Vault, { kind: "uups" });
  console.log("✓ storage layout validated against the network manifest");

  const vault = Vault.attach(proxy) as any;
  const iface = Vault.interface;
  const RELAYER_ROLE = ethers.id("RELAYER_ROLE");
  const OPERATOR_ROLE = ethers.id("OPERATOR_ROLE");

  // ── Phase 1: upgrade + single accepted token + role split ──
  const setAccepted = iface.encodeFunctionData("setAcceptedToken", [usdc, true]);
  const phase1: SafeTx[] = [
    { to: proxy, value: "0", data: iface.encodeFunctionData("upgradeToAndCall", [impl, setAccepted]) },
    { to: proxy, value: "0", data: iface.encodeFunctionData("grantRole", [RELAYER_ROLE, relayer]) },
    { to: proxy, value: "0", data: iface.encodeFunctionData("revokeRole", [OPERATOR_ROLE, relayer]) },
  ];

  // ── Phase 2: how much old CLRUSD is still out ──
  const oldClrusd = await vault.clrusd();
  const old = await ethers.getContractAt("IERC20MetadataUpgradeable", oldClrusd);
  const outstanding: bigint = await old.totalSupply();
  console.log(`Old CLRUSD ${oldClrusd}: ${ethers.formatUnits(outstanding, await old.decimals())} outstanding`);

  // ── Phase 3: re-point, only once drained ──
  const phase3: SafeTx[] = [];
  if (newClrusd) {
    const token = await ethers.getContractAt("ClearUSDUpgradeable", newClrusd);
    phase3.push({
      to: newClrusd,
      value: "0",
      data: token.interface.encodeFunctionData("grantMintAndBurnRoles", [proxy]),
    });
    phase3.push({ to: proxy, value: "0", data: iface.encodeFunctionData("setClrusd", [newClrusd]) });
    if (outstanding !== 0n) {
      console.log("! setClrusd will revert (ESADepositVaultTokenStillOutstanding) until the old supply is zero.");
    }
  }

  const out = path.join("deployments", network.name, "safe-batches");
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, "vault-1-upgrade.json"), JSON.stringify(batch(chainId, "Vault upgrade (H-3, M-5)", phase1), null, 2));
  if (phase3.length) {
    fs.writeFileSync(path.join(out, "vault-3-repoint.json"), JSON.stringify(batch(chainId, "Vault re-point to ClearUSDUpgradeable (M-7)", phase3), null, 2));
  }
  console.log(`Wrote Safe batches to ${out}. Review, then execute from the Ops Safe. Nothing was sent.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
