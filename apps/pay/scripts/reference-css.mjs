#!/usr/bin/env node
/**
 * Generates src/styles/reference.css from the Pay with Clear spec (docs/pay-reference/clear-pay-ref.html),
 * the way apps/rewards/scripts/reference-css.mjs does for rewards.
 *
 * The spec's modal frames (`.pw-modal`) and phone frames (`.sa-ph`: the link page and the bottom
 * sheet) are the app. This keeps, in the spec's own order, every rule whose classes are all used
 * inside one of them: the tokens, the base anatomy and the `pw-*` and `sa-*` components. Dropped: the
 * document's own chrome, the shop's pretend website (`.pw-site`), the merchant frames, dark mode (the
 * frames are light only), and exact repeats (the later copy wins, as in the browser).
 *
 * Overrides and decisions go in app.css, never here.
 *
 *   node apps/pay/scripts/reference-css.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SPEC = fileURLToPath(new URL('../../../docs/pay-reference/clear-pay-ref.html', import.meta.url));
const OUT = fileURLToPath(new URL('../src/styles/reference.css', import.meta.url));

const html = readFileSync(SPEC, 'utf8');
const css = html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>'));
const body = html.slice(html.indexOf('<body'));

// ---- The classes the phone frames use ----------------------------------------------------------
function phoneFrames(src) {
  const out = [];
  const open = /<div class="(sa-ph|pw-modal)[" ]/g;
  let m;
  while ((m = open.exec(src))) {
    let depth = 0;
    const tag = /<(\/?)div\b[^>]*>/g;
    tag.lastIndex = m.index;
    let t;
    while ((t = tag.exec(src))) {
      depth += t[1] ? -1 : 1;
      if (depth === 0) {
        out.push(src.slice(m.index, tag.lastIndex));
        break;
      }
    }
  }
  return out;
}
const frames = phoneFrames(body);
const used = new Set();
for (const f of frames) for (const c of f.matchAll(/class="([^"]*)"/g)) for (const k of c[1].split(/\s+/)) if (k) used.add(k);
// Classes the app adds to a frame's states that the drawings show only by their look.
for (const k of ['on', 'sa-ph', 'pw-modal']) used.add(k);

// ---- A small CSS reader: top-level rules and @-blocks ------------------------------------------
function blocks(src) {
  const out = [];
  let i = 0;
  const clean = src.replace(/\/\*[\s\S]*?\*\//g, '');
  while (i < clean.length) {
    const open = clean.indexOf('{', i);
    if (open < 0) break;
    const head = clean.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < clean.length && depth > 0) {
      if (clean[j] === '{') depth += 1;
      else if (clean[j] === '}') depth -= 1;
      j += 1;
    }
    out.push({ head, body: clean.slice(open + 1, j - 1).trim() });
    i = j;
  }
  return out;
}

const DOC_ONLY = /(^|[\s>+~,(])(h1|h2|h3|body|\.doc|\.note|\.lede|\.statelab|\.chg|\.sa-row|\.sa-wrap|\.sa-cap|\.sa-fit|\.sa-apis|\.sa-thumb|\.sa-mini)\b/;
function keepSelector(sel) {
  const s = sel.trim();
  if (!s) return false;
  if (s === ':root' || s === '*' || s === 'html' || /^\*::?(before|after)/.test(s)) return true;
  if (DOC_ONLY.test(` ${s}`)) return false;
  const classes = [...s.matchAll(/\.([A-Za-z_][\w-]*)/g)].map((m) => m[1]);
  if (classes.length === 0) return /^(button|input|svg|p|b|a|img|span)\b/.test(s);
  return classes.every((c) => used.has(c));
}

function filterRule(head, ruleBody) {
  const sels = head.split(',').filter(keepSelector);
  return sels.length ? `${sels.map((s) => s.trim()).join(',')}{${ruleBody.replace(/\s+/g, ' ').trim()}}` : null;
}

const kept = [];
for (const b of blocks(css)) {
  if (b.head.startsWith('@keyframes')) {
    kept.push(`${b.head}{${b.body.replace(/\s+/g, ' ')}}`);
    continue;
  }
  if (b.head.startsWith('@media')) {
    if (/prefers-color-scheme|max-width:\s*900px/.test(b.head)) continue;
    const inner = blocks(b.body).map((r) => filterRule(r.head, r.body)).filter(Boolean);
    if (inner.length) kept.push(`${b.head}{${inner.join('')}}`);
    continue;
  }
  if (b.head.startsWith('@')) continue;
  const r = filterRule(b.head, b.body);
  if (r) kept.push(r);
}

// Exact repeats: keep the last, where it falls in the order.
const seen = new Set();
const ordered = [];
for (let k = kept.length - 1; k >= 0; k -= 1) {
  if (seen.has(kept[k])) continue;
  seen.add(kept[k]);
  ordered.unshift(kept[k]);
}

const header = `/* Generated by apps/pay/scripts/reference-css.mjs from docs/pay-reference/clear-pay-ref.html. Do not edit: overrides go in app.css. ${frames.length} frames, ${used.size} classes, ${ordered.length} rules. */\n`;
writeFileSync(OUT, header + ordered.join('\n') + '\n');
console.log(`pay reference.css: ${frames.length} frames, ${used.size} classes, ${ordered.length} rules`);
